def test_every_pinned_leg_reaches_a_source_in_the_fragment():
    """The a3a10 invariant, read off the PDF's own table rather than the graph. Twelve legs
    since `cc_tasks/2026-09-12_a1_a8_b3_d4_sources.md` widened `RT.LEGS`; a leg that is allowed
    to reach no source is named in `tests/test_report_traceability.ALLOW_ZERO_SOURCES`, and
    while that mapping is empty this holds for every check the report carries."""
    got = rows(FRAGMENT.read_text(encoding="utf-8"))
    for leg in RT.LEGS:
        assert any(r["check"] == leg and r["doc"] for r in got), leg


def test_the_built_markdown_carries_the_fragment_verbatim():
    if not BUILT.is_file():
        pytest.skip("the report has not been built")
    frag = FRAGMENT.read_text(encoding="utf-8").rstrip("\n")
    assert frag in BUILT.read_text(encoding="utf-8")


def test_nothing_in_the_fragment_is_typed():
    """Every doc_id the fragment names is one the graph reaches for that leg; the check codes
    are the appendix legs and nothing else."""
    got = rows(FRAGMENT.read_text(encoding="utf-8"))
    assert {r["check"] for r in got} == set(RT.appendix_legs())
    framework = json.loads(RT.FRAMEWORK.read_text(encoding="utf-8"))
    evidenced = {}
    for e in framework["edges"]:
        if e["type"] == "EVIDENCED_BY":
            evidenced.setdefault(e["from"], set()).add(e["properties"]["doc_id"])
    for r in got:
        if r["doc"]:
            code = RT.FRAMEWORK_CODE.get(r["check"], r["check"])
            assert r["doc"] in evidenced.get(f"ind:{code}", set()), (r["check"], r["doc"])


