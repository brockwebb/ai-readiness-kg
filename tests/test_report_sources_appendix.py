def test_the_fragment_on_disk_is_what_the_graph_generates_now(session):
    """A stale fragment is a citation list from another revision of the graph."""
    text, report = RT.sources_appendix(session)
    assert text == FRAGMENT.read_text(encoding="utf-8")
    assert report["doc_ids_not_in_manifest"] == []


def test_a_doc_id_outside_the_manifest_is_refused_and_nothing_is_written(session, tmp_path):
    framework = json.loads(RT.FRAMEWORK.read_text(encoding="utf-8"))
    manifest = json.loads(RT.MANIFEST.read_text(encoding="utf-8"))["entries"]
    manifest = {k: v for k, v in manifest.items() if k != "w3c-dwbp-2017"}
    _text, report = RT.sources_appendix(session, framework, manifest)
    assert ("A3", "w3c-dwbp-2017") in report["doc_ids_not_in_manifest"]
    out = tmp_path / "sources_per_check.md"
    with pytest.raises(SystemExit, match="does not hold"):
        with pytest.MonkeyPatch.context() as mp:
            mp.setattr(RT, "MANIFEST", _write_manifest(tmp_path, manifest))
            RT.write_sources_appendix(session, out)
    assert not out.exists()


def _write_manifest(tmp_path: Path, entries: dict) -> Path:
    p = tmp_path / "manifest.json"
    p.write_text(json.dumps({"entries": entries}), encoding="utf-8")
    return p
