"""The published report cites its sources: the generated "Sources per check" appendix.

`cc_tasks/2026-09-11_report_sources_appendix.md` §3. "Citable by a stranger" means a stranger
holding the PDF. The appendix is generated by `report_traceability.sources_appendix` from the
graph, the framework of record and the corpus manifest; these tests hold its gate:

* the fragment exists, is included by the appendix section, and reaches the built markdown;
* every check the report carries has at least one row, and every row's doc_id is in the
  manifest;
* A3 and A10 carry their locators;
* the locator parser and the citation renderer behave on the shapes the evidence cells use;
* the prose-named product legs are read from the sections, not typed.

The graph-dependent cases skip when Neo4j is down, as the projection round-trip does; the
fragment-file cases do not.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts"))

import report_traceability as RT                                    # noqa: E402

FRAGMENT = REPO / "docs" / "reports" / "generated" / "sources_per_check.md"
SECTION = REPO / "docs" / "reports" / "sections" / "80_appendix.md"
BUILT = REPO / "docs" / "reports" / "2026-09_fss_ai_readiness_L0.md"
MANIFEST = json.loads((REPO / "corpus" / "manifest.json").read_text(encoding="utf-8"))["entries"]

ROW = re.compile(r"^\| (?P<check>[^|]+?) \| (?P<indicator>[^|]*?) \| (?P<source>.*?) \| "
                 r"(?P<doc>[^|]*?) \| (?P<locator>.*?) \|$")


def rows(text: str) -> list:
    out = []
    for line in text.splitlines():
        m = ROW.match(line)
        if m and m.group("check") not in ("Check", "---"):
            d = m.groupdict()
            d["doc"] = d["doc"].strip("` ")
            out.append(d)
    return out


# ------------------------------------------------------------------ the fragment on disk
def test_the_fragment_exists_and_the_appendix_section_includes_it():
    assert FRAGMENT.is_file(), "run scripts/build_l0_report.py; the builder writes it"
    assert "<!-- include: sources_per_check -->" in SECTION.read_text(encoding="utf-8")
    # inside the numerals-exempt region, like the other generated method tables
    sec = SECTION.read_text(encoding="utf-8")
    assert sec.index("<!-- lint: numerals-exempt -->") < sec.index("include: sources_per_check") \
        < sec.index("<!-- lint: numerals-enforced -->")


def test_every_check_the_report_carries_has_a_row():
    got = {r["check"] for r in rows(FRAGMENT.read_text(encoding="utf-8"))}
    want = set(RT.appendix_legs())
    assert want <= got, sorted(want - got)


def test_every_row_doc_id_is_in_the_manifest():
    bad = [r for r in rows(FRAGMENT.read_text(encoding="utf-8")) if r["doc"] and r["doc"] not in MANIFEST]
    assert not bad, [(r["check"], r["doc"]) for r in bad]


def test_a3_and_a10_rows_carry_their_locators():
    by = {}
    for r in rows(FRAGMENT.read_text(encoding="utf-8")):
        by.setdefault(r["check"], {})[r["doc"]] = r["locator"]
    assert "BP 17" in by["A3"]["w3c-dwbp-2017"]
    assert "downloadURL" in by["A3"]["dcat-us-1-1-schema"]
    assert "A1 and A1.1" in by["A3"]["wilkinson-2016-fair-guiding-principles"]
    assert "BP 9" in by["A10"]["w3c-dwbp-2017"] and "BP 27" in by["A10"]["w3c-dwbp-2017"]
    assert "F1" in by["A10"]["wilkinson-2016-fair-guiding-principles"]


