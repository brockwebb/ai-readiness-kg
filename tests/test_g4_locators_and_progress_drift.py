"""G4's two sources carry a locator a stranger can turn to, and `docs/progress/` is compared
to the record it is a view of.

`cc_tasks/2026-09-19_g4_locators_and_progress_drift.md`, decisions 1 to 4.

Two guards, one file, because they are the same rule applied twice: **a generated consumer is
compared to its source, and a citation is checked against the document rather than believed.**

* **The locator half** (decisions 1 to 3). G4's Evidence cell is the authored source of the
  sources-appendix Locator column. A cell that names a document and no place in it is a
  citation with no page number — DN-001's floor is that a stranger can follow it. So every
  double-quoted span in the cell must be verbatim from the document it is attached to, checked
  through `kg/extraction/grounding.py`, the same validator invariant 3 holds every extracted
  node to. Nothing here is typed: the quotes are READ from the framework of record, and the
  record is asserted equal to the skeleton cell that authors it.

  A clause the document does not support gets the words `general support; no pinpoint`, never
  an invented locator, so the three legal outcomes of decision 2 are all expressible and only
  the silent fourth — a Source column filled and a Locator column empty — fails.

  **Two renderings, one document.** These two sources are PDFs. `state/docling_md/` holds the
  layout-aware Docling conversion (the reading substrate, `scripts/t1_build_index.py --phase
  convert`); `run_bulk_extraction.doc_text` reads PDFs through `pypdf`, because
  `kg.ingest.gate.substrate_path` returns None for them by design. Both are lossy views of the
  same sha256-verified bytes and they do NOT agree character for character: the Working Paper's
  Introduction carries U+2019 in `agency's`, which Docling normalises to an ASCII apostrophe
  and NFKC does not map. A span is grounded when it grounds in a rendering that is on disk,
  and the assertion message names the result per rendering, so a quote nobody can find in any
  rendering fails and a converter idiosyncrasy does not force the citation to be truncated
  mid-sentence to avoid a character.

  Both renderings are gitignored, rebuildable projections. A document with neither on disk
  skips, naming the command that rebuilds one — the convention the Neo4j-backed tests use.

* **The drift half** (decision 4). `docs/progress/` is generated by `scripts/framework_progress
  .py --cycle <cycle>` from `framework/ai_readiness_framework.json`. `tests/test_scan_run_2.py`
  ties the page to the cycle of record's denominator and nothing tied it to the framework
  record: the 2026-09-19 re-snapshot's regeneration moved counts that had been wrong on the
  page since 2026-09-11 and no test had noticed (`cc_tasks/2026-09-19_resnapshot_rj4_RESULT.md`
  §5). This is the standard generated-file-is-up-to-date gate — `go generate` then `git diff
  --exit-code`, Bazel's `diff_test`, `make -q` — regenerate into a scratch directory and
  byte-compare. The negative control below is the guard replaying what it is built for: one
  count edited by hand, and the message that names it.
"""
