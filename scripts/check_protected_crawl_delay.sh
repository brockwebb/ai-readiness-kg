#!/usr/bin/env bash
. "$(dirname "$0")/check_protected_lib.sh"
# The write set of `cc_tasks/2026-10-11_manners_honours_crawl_delay.md`, asserted against the
# commit the task started from (default e6d9b43e, HEAD when it was launched), so it reads the
# same before and after the task's own commit.
#
# The task's write set: `manners.py` (decision 4, for Crawl-delay alone), `params.yaml`
# (`manners.crawl_delay_max_s` and nothing else), the fixture tests, this script, the RESULT.
# Widened, each for the reason the RESULT gives:
#
#   * `scripts/build_evidence_map.py`: it read the cycle of record under TODAY's params.yaml and
#     refused on any difference, so the new key made the map unbuildable. It now recovers the
#     cycle's params from git by hash (DD-052 §3, DD-064 §2), which was the claim's stated intent.
#   * `docs/evidence/claims.yaml`, `docs/brief/E_architecture.md`: derived views that cite
#     source LINE numbers in `manners.py`, regenerated by their own generators.
#   * `tests/test_adopter_path.py`: one test compared the snapshot payload's `params_hash` to
#     TODAY's params.yaml, so the new key turned it red; it now recovers the snapshot's params
#     by hash (`tests/support/prior_params.py`), and every other assertion in it is unchanged.
#   * `tests/conftest.py`: the autouse restore of `chunked_pilot`'s globals now restores
#     `run_bulk_extraction`'s too. A pre-existing leak (reproduced at e6d9b43e) that the new test
#     file's shift of xdist's distribution turned into a red gate.
#
# Byte-identical: every rule, collector, `run.py`, `runner.py`, `errors.py`, `model.py`,
# `scripts/score.py`, every stored payload, the framework record, the event log and every task
# file.
set -u
cd "$(dirname "$0")/.." || exit 2
BASE="${1:-e6d9b43e}"
PY="${PY:-/opt/anaconda3/bin/python3}"
fail=0

changed_and_new() {
  { git diff --name-only "$BASE" -- "$@"; git ls-files --others --exclude-standard -- "$@"; } \
    | sed '/^$/d' | sort -u
}

allowed() {
  case "$1" in
    assessment/harness/scan/manners.py|assessment/harness/scan/params.yaml) return 0 ;;
    tests/test_manners_crawl_delay.py|scripts/check_protected_crawl_delay.sh) return 0 ;;
    scripts/build_evidence_map.py|tests/test_adopter_path.py|tests/conftest.py) return 0 ;;
    docs/evidence/claims.yaml|docs/brief/E_architecture.md) return 0 ;;
    seldon_events.jsonl) return 0 ;;
    cc_tasks/2026-10-11_manners_honours_crawl_delay_RESULT.md) return 0 ;;
  esac
  return 1
}

# A task file ADDED since the base was committed by a registration (`seldon cc register`), not
# by this session; registrations landed on main while this task ran (e224d58d, 92b687bb). It is
# not in the write set and is not a violation. A MODIFIED task file still is (below).
added_tasks=$(git diff --name-only --diff-filter=A "$BASE" -- 'cc_tasks/*.md')
while IFS= read -r path; do
  [ -z "$path" ] && continue
  printf '%s\n' "$added_tasks" | grep -qxF "$path" && continue
  allowed "$path" || { echo "FAIL path outside the write set moved: $path"; fail=1; }
done < <(changed_and_new .)

for p in assessment/harness/scan/rules assessment/harness/scan/collectors \
         assessment/harness/scan/run.py assessment/harness/scan/runner.py \
         assessment/harness/scan/errors.py assessment/harness/scan/model.py \
         scripts/score.py state events framework/ai_readiness_framework.json \
         corpus/manifest.json docs/reports; do
  if [ -n "$(changed_and_new "$p")" ]; then echo "FAIL $p must be byte-identical and moved"; fail=1; fi
done

# Every task file other than this task's RESULT: immutable once written.
moved_tasks=$(git diff --name-only --diff-filter=MDR "$BASE" -- cc_tasks/ \
  | grep -vxF 'cc_tasks/2026-10-11_manners_honours_crawl_delay_RESULT.md' || true)
if [ -n "$moved_tasks" ]; then echo "FAIL a task file moved: $moved_tasks"; fail=1; fi

# Append-only: the Seldon store.
removed=$(git diff "$BASE" -- seldon_events.jsonl | grep -c '^-[^-]' || true)
if [ "$removed" -ne 0 ]; then echo "FAIL seldon_events.jsonl lost or changed $removed line(s)"; fail=1; fi

# params.yaml: `manners.crawl_delay_max_s` (= 60) and nothing else.
"$PY" - "$BASE" <<'EOF' || fail=1
import subprocess, sys, yaml
base = sys.argv[1]
then = yaml.safe_load(subprocess.run(
    ["git", "show", f"{base}:assessment/harness/scan/params.yaml"],
    capture_output=True, text=True, check=True).stdout)
now = yaml.safe_load(open("assessment/harness/scan/params.yaml", encoding="utf-8"))
bad = 0
if now["manners"].pop("crawl_delay_max_s", None) != 60:
    print("FAIL manners.crawl_delay_max_s is not 60"); bad = 1
if then != now:
    print("FAIL params.yaml moved beyond manners.crawl_delay_max_s"); bad = 1
sys.exit(bad)
EOF

# The regenerated views are their generators' output exactly.
"$PY" scripts/build_evidence_map.py --check >/dev/null 2>&1 \
  || { echo "FAIL docs/evidence/claims.yaml drifts from its generator"; fail=1; }
"$PY" scripts/build_brief_pack.py --check >/dev/null 2>&1 \
  || { echo "FAIL docs/brief drifts from its generator"; fail=1; }

if [ "$fail" -eq 0 ]; then echo "PROTECTED PATHS: PASS"; else echo "PROTECTED PATHS: FAIL"; fi
exit "$fail"
